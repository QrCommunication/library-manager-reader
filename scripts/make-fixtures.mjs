// Generates the committed dev fixtures:
//   assets/fixtures/sample.epub        — minimal valid EPUB 3 (2 chapters)
//   assets/fixtures/sample.cbz         — ZIP of three 1x1 PNG pages
//   src/dev/fixtures.generated.ts      — both zips as base64 TS constants
// Run: node scripts/make-fixtures.mjs
import { zipSync, strToU8 } from 'fflate';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fixturesDir = path.join(root, 'assets', 'fixtures');
const devDir = path.join(root, 'src', 'dev');

// Minimal valid 1x1 PNG (transparent black), embedded as base64.
const PNG_1X1_B64 =
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==';
const PNG_1X1 = new Uint8Array(Buffer.from(PNG_1X1_B64, 'base64'));

const CONTAINER_XML = `<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>
`;

const CONTENT_OPF = `<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="bookid">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="bookid">urn:uuid:00000000-0000-0000-0000-000000000001</dc:identifier>
    <dc:title>Sample EPUB</dc:title>
    <dc:language>en</dc:language>
    <meta property="dcterms:modified">2026-01-01T00:00:00Z</meta>
  </metadata>
  <manifest>
    <item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>
    <item id="ch1" href="ch1.xhtml" media-type="application/xhtml+xml"/>
  </manifest>
  <spine>
    <itemref idref="nav"/>
    <itemref idref="ch1"/>
  </spine>
</package>
`;

const NAV_XHTML = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
<head>
  <title>Table of contents</title>
  <meta charset="utf-8"/>
</head>
<body>
  <nav epub:type="toc">
    <ol>
      <li><a href="ch1.xhtml#c1">Chapter 1</a></li>
      <li><a href="ch1.xhtml#c2">Chapter 2</a></li>
    </ol>
  </nav>
</body>
</html>
`;

const CH1_XHTML = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE html>
<html xmlns="http://www.w3.org/1999/xhtml">
<head>
  <title>Sample EPUB</title>
  <meta charset="utf-8"/>
</head>
<body>
  <h1 id="c1">Chapter 1</h1>
  <p>This is the first paragraph of the sample book. It exists so that a fresh
  development install has something readable to open, swipe through and paginate.</p>
  <p>The quick brown fox jumps over the lazy dog, again and again, filling just
  enough space for the reader engine to lay out a couple of pages on a phone
  screen.</p>
  <p>Turn the page to reach the second chapter.</p>
  <h1 id="c2">Chapter 2</h1>
  <p>This is the second chapter of the sample book. Two headings give the table
  of contents two entries to display.</p>
  <p>A few more sentences pad the chapter so the pagination engine has real
  content to measure while running under the Maestro smoke test.</p>
  <p>End of the sample book. Thanks for reading.</p>
</body>
</html>
`;

// mimetype MUST be the first entry and stored uncompressed (EPUB spec / OCF).
// fflate preserves object key order, and per-file { level: 0 } stores it raw.
const epub = zipSync({
  mimetype: [strToU8('application/epub+zip'), { level: 0 }],
  'META-INF/container.xml': strToU8(CONTAINER_XML),
  'OEBPS/content.opf': strToU8(CONTENT_OPF),
  'OEBPS/nav.xhtml': strToU8(NAV_XHTML),
  'OEBPS/ch1.xhtml': strToU8(CH1_XHTML),
});

const cbz = zipSync({
  '001.png': [PNG_1X1, { level: 0 }],
  '002.png': [PNG_1X1, { level: 0 }],
  '003.png': [PNG_1X1, { level: 0 }],
});

const toB64 = (u8) => Buffer.from(u8).toString('base64');

const generated = `// Generated by scripts/make-fixtures.mjs — do not edit.
export const SAMPLE_EPUB_B64 =
  '${toB64(epub)}';

export const SAMPLE_CBZ_B64 =
  '${toB64(cbz)}';
`;

await mkdir(fixturesDir, { recursive: true });
await mkdir(devDir, { recursive: true });
await writeFile(path.join(fixturesDir, 'sample.epub'), epub);
await writeFile(path.join(fixturesDir, 'sample.cbz'), cbz);
await writeFile(path.join(devDir, 'fixtures.generated.ts'), generated);

console.log(`sample.epub ${epub.length} B, sample.cbz ${cbz.length} B, fixtures.generated.ts written`);
