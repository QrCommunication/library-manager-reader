import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url)) + '/..';
const outfile = join(root, '.engine-out/engine-bundle.js');

// Literata embedded as base64 for @font-face inside the WebView
const literataB64 = readFileSync(
  join(root, 'node_modules/@fontsource/literata/files/literata-latin-400-normal.woff2'),
).toString('base64');

await build({
  entryPoints: [join(root, 'src/engine/engine.ts')],
  bundle: true,
  format: 'iife',
  minify: true,
  outfile,
  define: { __LITERATA_B64__: JSON.stringify(literataB64) },
  logLevel: 'info',
});

const code = readFileSync(outfile, 'utf8');
writeFileSync(
  join(root, 'src/engine/engineHtml.ts'),
  '// Generated by scripts/build-engine.mjs — do not edit.\n' +
  'export const __LITERATA_B64__ = ' + JSON.stringify(literataB64) + ';\n' +
  'export const ENGINE_BUNDLE = ' + JSON.stringify(code) + ';\n\n' +
  'export function buildEngineHtml(): string {\n' +
  "  return '<!doctype html><html><head><meta charset=\"utf-8\">' +\n" +
  "    '<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, user-scalable=no\">' +\n" +
  "    '<style>@font-face{font-family:Literata;src:url(data:font/woff2;base64,' + __LITERATA_B64__ + ') format(\"woff2\");}</style>' +\n" +
  "    '</head><body><div id=\"book\"></div><script>' + ENGINE_BUNDLE + '</script></body></html>';\n" +
  '}\n',
);
console.log('engine html generated');
