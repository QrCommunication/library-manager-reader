import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url)) + '/..';
const outfile = join(root, '.engine-out/engine-bundle.js');

// Reading fonts embedded as base64 for @font-face inside the WebView (offline-first:
// the whole font set ships in the bundle — Literata serif, Lexend reading fluency,
// Atkinson Hyperlegible low-vision, OpenDyslexic dyslexia; all SIL OFL licensed)
const literataB64 = readFileSync(
  join(root, 'node_modules/@fontsource/literata/files/literata-latin-400-normal.woff2'),
).toString('base64');
const lexendB64 = readFileSync(
  join(root, 'node_modules/@fontsource/lexend/files/lexend-latin-400-normal.woff2'),
).toString('base64');
const atkinsonB64 = readFileSync(
  join(root, 'node_modules/@fontsource/atkinson-hyperlegible/files/atkinson-hyperlegible-latin-400-normal.woff2'),
).toString('base64');
const openDyslexicB64 = readFileSync(
  join(root, 'assets/fonts/OpenDyslexic-Regular.woff2'),
).toString('base64');

// node-unrar-js wasm embedded as base64: the WebView html has no base URL, so unrar's
// default locateFile("unrar.wasm") + fetch/XHR could never resolve. Inlined via define
// and handed to createExtractorFromData({ wasmBinary }) — zero network at runtime.
const unrarWasmB64 = readFileSync(
  join(root, 'node_modules/node-unrar-js/esm/js/unrar.wasm'),
).toString('base64');

await build({
  entryPoints: [join(root, 'src/engine/engine.ts')],
  bundle: true,
  format: 'iife',
  minify: true,
  outfile,
  define: {
    __LITERATA_B64__: JSON.stringify(literataB64),
    __UNRAR_WASM_B64__: JSON.stringify(unrarWasmB64),
  },
  logLevel: 'info',
});

const code = readFileSync(outfile, 'utf8');
writeFileSync(
  join(root, 'src/engine/engineHtml.ts'),
  '// Generated by scripts/build-engine.mjs — do not edit.\n' +
  'export const __LITERATA_B64__ = ' + JSON.stringify(literataB64) + ';\n' +
  'export const __LEXEND_B64__ = ' + JSON.stringify(lexendB64) + ';\n' +
  'export const __ATKINSON_B64__ = ' + JSON.stringify(atkinsonB64) + ';\n' +
  'export const __OPENDYSLEXIC_B64__ = ' + JSON.stringify(openDyslexicB64) + ';\n' +
  'export const ENGINE_BUNDLE = ' + JSON.stringify(code) + ';\n\n' +
  'export function buildEngineHtml(): string {\n' +
  "  return '<!doctype html><html><head><meta charset=\"utf-8\">' +\n" +
  "    '<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, user-scalable=no\">' +\n" +
  "    '<style>' +\n" +
  "    'html,body{height:100%;margin:0;}' +\n" +
  "    // sized chain down to #book, else the foliate view collapses to 0 height\n" +
  "    '#book{width:100%;height:100%;box-sizing:border-box;}' +\n" +
  "    '@font-face{font-family:Literata;src:url(data:font/woff2;base64,' + __LITERATA_B64__ + ') format(\"woff2\");}' +\n" +
  "    '@font-face{font-family:Lexend;src:url(data:font/woff2;base64,' + __LEXEND_B64__ + ') format(\"woff2\");}' +\n" +
  "    '@font-face{font-family:\"Atkinson Hyperlegible\";src:url(data:font/woff2;base64,' + __ATKINSON_B64__ + ') format(\"woff2\");}' +\n" +
  "    '@font-face{font-family:OpenDyslexic;src:url(data:font/woff2;base64,' + __OPENDYSLEXIC_B64__ + ') format(\"woff2\");}' +\n" +
  "    '</style>' +\n" +
  "    '</head><body><div id=\"book\"></div><script>' + ENGINE_BUNDLE + '</script></body></html>';\n" +
  '}\n',
);
console.log('engine html generated');
